"""The registration surface a plugin's setup function receives."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class SeleneSpacePluginAPI(Protocol):
    """Exactly fourteen register_* methods, one per capability slot."""

    def register_exchange(self, name: str, adapter: Any) -> None: ...

    def register_strategy(self, name: str, strategy: Any) -> None: ...

    def register_indicator(self, name: str, indicator: Any) -> None: ...

    def register_llm_provider(self, name: str, provider: Any) -> None: ...

    def register_channel(self, name: str, channel: Any) -> None: ...

    def register_tool(self, name: str, tool: Any) -> None: ...

    def register_hook(self, event: str, handler: Any) -> None: ...

    def register_risk_rule(self, name: str, rule: Any) -> None: ...

    def register_metric(
        self, name: str, metric_type: Any, description: str = ""
    ) -> None: ...

    def register_health_check(self, name: str, check: Any) -> None: ...

    def register_command(self, name: str, command: Any) -> None: ...

    def register_middleware(self, name: str, middleware: Any) -> None: ...

    def register_mcp_server(self, name: str, server: Any) -> None: ...

    def register_skill(self, name: str, skill: Any) -> None: ...
