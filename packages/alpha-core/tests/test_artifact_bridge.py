"""Tests for the external artifact bridge.

Two things here are load-bearing beyond ordinary coverage:

1. :func:`test_operator_windows_match_the_implementations` pins the window each
   rolling operator actually rolls. Windows are literals inside the operator
   bodies, so this table is the oracle: change ``op_ts_std`` to ``window=7`` and
   this test must fail. Without it, every windowed producer name would be judged
   against a stale number and artifacts would be silently accepted or silently
   blocked.
2. :func:`test_json_artifact_without_decoded_formula_raises` covers the refusal
   path. Producer token ids index a foreign vocabulary, so guessing names from
   ids would produce a formula that runs and reports wrong numbers.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from selene_space_alpha.artifact_bridge import (
    UnsupportedArtifact,
    classify,
    names_from_json,
    names_from_py_header,
    operator_windows,
    parse_py_header,
    resolve,
    to_tokens,
)
from selene_space_alpha.vm.vm_pandas import PandasStackVM

#: Windows as they are written into the operator bodies in ``ops/ops_pandas.py``.
#: Deliberately duplicated: if either the source literal or the extraction
#: changes, the two disagree and this test fails.
EXPECTED_WINDOWS = {
    "TS_MEAN": 5,
    "TS_STD": 5,
    "TS_RANK": 20,
    "TS_CORR": 20,
    "TS_MAX": 10,
    "TS_MIN": 10,
    "TS_DELTA": 1,
}

_ARB_NAMES = [
    "ICHIMOKU_KIJUN_DEV",
    "GK_VOL",
    "RET_ENTROPY_20",
    "RVOL",
    "MUL",
    "TS_MIN_10",
    "GATE",
    "SIGN",
]

_ARB_HEADER = '''"""ARBUSDT Auto V2 Factor

Auto-generated by alphamaster_pipeline v2gen v2gen-template-1.0.0:
  formula (RPN ids): [53, 37, 62, 6, 84, 107, 89, 88]
  formula (names):   ICHIMOKU_KIJUN_DEV -> GK_VOL -> RET_ENTROPY_20 -> RVOL -> MUL -> TS_MIN_10 -> GATE -> SIGN
  source score: 2.503889560699463 | vocab: v71099e94f275 | formula_sha: 4e7dde10fd02
"""

import sys
'''


def test_operator_windows_match_the_implementations() -> None:
    windows = operator_windows()
    for operator, expected in EXPECTED_WINDOWS.items():
        assert windows.get(operator) == expected, (
            f"{operator} rolls window={windows.get(operator)}, table says {expected} — "
            "either the operator body or operator_windows() changed"
        )


def test_ts_std_20_operator_declares_window_20() -> None:
    """The dedicated variant must be inspectable by operator_windows() so a
    future TS_STD_30-style artifact name still meets a real gate."""
    assert operator_windows().get("TS_STD_20") == 20


def test_operator_windows_excludes_non_rolling_operators() -> None:
    windows = operator_windows()
    for name in ("ADD", "MUL", "SIGN", "GATE", "RANK"):
        assert name not in windows


# --- classifier: one case per status ----------------------------------------


def test_feature_name_is_confirmed_with_token() -> None:
    verdict = classify("RET")
    assert verdict.kind == "feature"
    assert verdict.status == "CONFIRMED"
    assert verdict.token == 0


def test_operator_name_is_confirmed_with_token() -> None:
    verdict = classify("MUL")
    assert verdict.kind == "operator"
    assert verdict.status == "CONFIRMED"
    assert verdict.token is not None


def test_windowed_name_matching_the_implementation_is_window_ok() -> None:
    verdict = classify("TS_MIN_10")
    assert verdict.kind == "operator"
    assert verdict.status == "WINDOW_OK"
    assert verdict.token == classify("TS_MIN").token


def test_windowed_name_with_a_dedicated_variant_operator_is_confirmed() -> None:
    """TS_STD_20 became a first-class operator (alpha artifact bridge); the
    5-bar TS_STD must still never answer a 20-bar request — TS_STD_30 proves
    the window gate survives."""
    verdict = classify("TS_STD_20")
    assert verdict.kind == "operator"
    assert verdict.status == "CONFIRMED"
    assert verdict.token is not None
    assert verdict.token != classify("TS_STD").token

    mismatch = classify("TS_STD_30")
    assert mismatch.status == "WINDOW_MISMATCH"
    assert mismatch.token is None, "a 5-bar std must never answer a 30-bar request"

    plain = classify("TS_STD")
    assert plain.kind == "operator"
    assert plain.status == "CONFIRMED"


def test_unknown_name_is_missing() -> None:
    verdict = classify("DEFINITELY_NOT_A_TOKEN")
    assert verdict.kind == "missing"
    assert verdict.status == "MISSING"
    assert verdict.token is None


def test_trailing_digits_without_a_known_stem_are_not_a_window_match() -> None:
    """``CHAIKIN_3_10`` must not be read as operator ``CHAIKIN_3`` window 10."""
    for name in ("CHAIKIN_3_10", "HURST_50", "SLOPE20", "SIGNED_POWER_2"):
        assert classify(name).status == "MISSING", name


# --- resolution -------------------------------------------------------------


def test_resolve_reports_every_name_in_chain_order() -> None:
    verdicts = resolve(_ARB_NAMES)
    assert [v.name for v in verdicts] == _ARB_NAMES
    assert [v.status for v in verdicts] == [
        "CONFIRMED",
        "CONFIRMED",
        "CONFIRMED",
        "CONFIRMED",
        "CONFIRMED",
        "WINDOW_OK",
        "CONFIRMED",
        "CONFIRMED",
    ]


def test_to_tokens_refuses_a_partially_resolved_chain() -> None:
    with pytest.raises(UnsupportedArtifact) as excinfo:
        to_tokens(resolve(["ICHIMOKU_KIJUN_DEV", "DEFINITELY_NOT_A_TOKEN", "MUL"]))
    assert "DEFINITELY_NOT_A_TOKEN" in str(excinfo.value)
    assert "MISSING" in str(excinfo.value)


def test_to_tokens_maps_a_fully_usable_chain() -> None:
    tokens = to_tokens(resolve(["RET", "TS_MIN_10", "MUL"]))
    assert tokens == [0, classify("TS_MIN").token, classify("MUL").token]


# --- name extraction --------------------------------------------------------


def test_json_names_come_from_the_decoded_chain() -> None:
    payload = {
        "vocab_version": "v71099e94f275",
        "formula": [81, 44, 123],
        "formula_decoded": "CHAIKIN_3_10 → AD_LINE_SLOPE → SIGNED_POWER_2",
    }
    assert names_from_json(payload) == [
        "CHAIKIN_3_10",
        "AD_LINE_SLOPE",
        "SIGNED_POWER_2",
    ]


def test_json_names_accept_ascii_arrow() -> None:
    payload = {"formula_decoded": "RET -> TS_MIN_10"}
    assert names_from_json(payload) == ["RET", "TS_MIN_10"]


def test_json_artifact_without_decoded_formula_raises() -> None:
    with pytest.raises(UnsupportedArtifact):
        names_from_json({"formula": [81, 44, 123]})
    with pytest.raises(UnsupportedArtifact):
        names_from_json({"formula_decoded": "   "})


def test_py_header_is_read_from_the_docstring() -> None:
    header = parse_py_header(_ARB_HEADER)
    assert header.names == _ARB_NAMES
    assert header.template == "1.0.0"
    assert header.vocab == "v71099e94f275"
    assert header.formula_sha == "4e7dde10fd02"


def test_py_source_without_a_header_is_not_an_artifact() -> None:
    source = '"""A hand-written strategy."""\n\nimport math\n'
    with pytest.raises(UnsupportedArtifact):
        names_from_py_header(source)


def test_py_source_that_is_not_valid_python_raises() -> None:
    with pytest.raises(UnsupportedArtifact):
        parse_py_header("def broken(:\n")


# --- handoff: names -> tokens -> an executed series ------------------------


def _synthetic_panel(n: int = 200) -> pd.DataFrame:
    """A deterministic OHLCV frame, so nothing here touches an external path."""
    rng = np.random.default_rng(7)
    close = pd.Series(100.0 + np.cumsum(rng.normal(0, 1, n)))
    return pd.DataFrame(
        {
            "open": close.shift(1).fillna(close.iloc[0]),
            "high": close + rng.uniform(0, 1, n),
            "low": close - rng.uniform(0, 1, n),
            "close": close,
            "volume": rng.uniform(1000, 5000, n),
        }
    )


def test_resolved_names_execute_to_a_live_series() -> None:
    """A resolved chain is a real formula, not just a list of plausible ints.

    ``PandasStackVM.execute`` returns ``None`` both for a malformed chain and
    for a chain whose features degraded to zero Series, so asserting non-None
    alone would pass on a silently-degenerate formula. The spread assertion is
    the one that bites — a zero-filled result has ``nunique == 1``.
    """
    tokens = to_tokens(resolve(["RET", "RET", "TS_MIN_10", "MUL"]))
    result = PandasStackVM().execute(tokens, _synthetic_panel())
    assert result is not None
    assert len(result) == 200
    assert result.nunique() > 1
