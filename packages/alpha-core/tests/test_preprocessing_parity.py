"""Golden-fixture parity for the 13 sklearn-bridged neutralize methods.

Compares the Selene pandas port against fixtures generated by the real
AlphaPurify polars implementations (scripts/gen_preprocessing_fixtures.py).

Guard: exact ``sklearn_version`` match -> strict tolerance 1e-6; mismatch ->
relaxed 1e-2 but still compared (never silently skipped). Tests only read the
fixtures via pandas/pyarrow — they never import AlphaPurify or polars.
"""
from __future__ import annotations

import ast
import json
import pathlib

import numpy as np
import pandas as pd
import pytest
import sklearn

from selene_space_factor_research.preprocessing import METHOD_REGISTRY

FIX = pathlib.Path(__file__).parent / "fixtures" / "preprocessing"

# Only the 13 sklearn-bridged methods get golden fixtures. multiOLS and
# partialcorrelation are pure numpy/scipy and live in test_preprocessing_reference.py.
SKLEARN_METHODS = [
    "neutralize_lasso",
    "neutralize_ridge",
    "neutralize_elasticnet",
    "neutralize_polynomial",
    "neutralize_kernelridge",
    "neutralize_huber",
    "neutralize_ransac",
    "neutralize_theilsen",
    "neutralize_random_forest",
    "neutralize_GBDT",
    "neutralize_PCA",
    "neutralize_ICA",
    "neutralize_bayesianridge",
]


def _meta() -> dict:
    return json.loads((FIX / "meta.json").read_text(encoding="utf-8"))


def _guard_tolerance(meta: dict) -> tuple[float, str]:
    """Guard-key mechanism: exact match -> strict, else relaxed (still compare)."""
    fixture_v = meta["sklearn_version"]
    running = sklearn.__version__
    if running == fixture_v:
        return float(meta["tolerance"]["strict"]), f"strict 1e-6 (sklearn {running} == fixture {fixture_v})"
    return float(meta["tolerance"]["relaxed"]), (
        f"relaxed 1e-2 (running {running} != fixture {fixture_v})"
    )


def _quadrant_files() -> list[tuple[str, dict]]:
    meta = _meta()
    out = []
    for key in SKLEARN_METHODS:
        for q in meta["quadrants"]:
            out.append(
                (
                    key,
                    {
                        "scale_X": q["scale_X"],
                        "dummy_cols": q["dummy_cols"] or None,
                        "file": meta["methods"][key]["quadrants"][
                            f"scaleX_{str(q['scale_X']).lower()}_dummy_{q['dummy']}"
                        ],
                        "params": meta["methods"][key]["params"],
                    },
                )
            )
    return out


def test_fixture_meta_shape() -> None:
    meta = _meta()
    assert len(meta["methods"]) == 13
    for key in SKLEARN_METHODS:
        assert len(meta["methods"][key]["quadrants"]) == 4
    assert set(meta["tolerance"]) == {"strict", "relaxed"}


def test_fixture_input_is_finite() -> None:
    inp = pd.read_parquet(FIX / "input.parquet")
    assert not inp.select_dtypes(include="number").isna().any().any()
    assert len(inp) == 250


def test_guard_matches_fixture() -> None:
    meta = _meta()
    tol, mode = _guard_tolerance(meta)
    if sklearn.__version__ == meta["sklearn_version"]:
        assert tol == 1e-6
        assert "strict" in mode


def test_parity_imports_no_polars_or_alphapurify() -> None:
    tree = ast.parse(pathlib.Path(__file__).read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            for alias in node.names:
                root = alias.name.split(".")[0]
                assert root not in ("polars", "alphapurify"), f"banned import {alias.name}"


@pytest.mark.parametrize("key,quad", _quadrant_files())
def test_neutralize_golden_parity(key: str, quad: dict) -> None:
    meta = _meta()
    cols = meta["columns"]
    inp = pd.read_parquet(FIX / "input.parquet")
    expected = pd.read_parquet(FIX / "expected" / quad["file"])

    fn = METHOD_REGISTRY[key].func
    got = fn(
        inp,
        trade_date_col=cols["trade_date_col"],
        factor_col=cols["factor_col"],
        neutralizer_cols=cols["neutralizer_cols"],
        dummy_cols=quad["dummy_cols"],
        scale_X=quad["scale_X"],
        **quad["params"],
    )

    t_col, s_col, f_col = cols["trade_date_col"], cols["symbol_col"], cols["factor_col"]
    g = got.set_index([t_col, s_col])[f_col].sort_index()
    e = expected.set_index([t_col, s_col])[f_col].sort_index()
    # Never silently skip: row sets must match exactly.
    assert g.index.equals(e.index), f"{key} {quad['file']}: row alignment mismatch"

    diff = (g - e).abs()
    tol, mode = _guard_tolerance(meta)
    maxdiff = float(diff.max()) if len(diff) else np.nan
    assert maxdiff <= tol, (
        f"{key} {quad['file']} [{mode}]: maxdiff={maxdiff:.3e} > tol={tol}"
    )
