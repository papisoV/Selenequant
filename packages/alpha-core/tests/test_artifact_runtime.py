"""Tests for the artifact runtime consumer (bridge: load path).

Four load-bearing cases per the design review (S3):

1. Success path: an ARB-shaped header loads into a runnable
   :class:`AlphaFormulaStrategy` with SIGN-chain thresholds 0.6/0.4.
2. Missing-name path: an unresolvable name raises ``UnsupportedArtifact``
   listing every blocked name — never a partial guess.
3. Terminal-stack gate: under an *intermediate* vocabulary where TS_STD_20
   was (wrongly) a feature instead of an operator, the PENGU chain reduces
   to a terminal stack of 2 and must be refused. This is the regression
   proof for the review-caught bug: feature-izing TS_STD_20 would let the
   chain "run" with the VM returning None mid-chain and silently degrade.
4. Header-less source errors clearly instead of guessing.
"""

from __future__ import annotations

import pytest

from selene_space_alpha.artifact_bridge import UnsupportedArtifact
from selene_space_alpha.artifact_runtime import (
    default_thresholds,
    load_artifact_strategy,
    rpn_stack_gate,
)
from selene_space_alpha.strategy_bridge import AlphaFormulaStrategy
from selene_space_alpha.vocab import FEATURE_NAMES, FORMULA_VOCAB, FormulaVocab

