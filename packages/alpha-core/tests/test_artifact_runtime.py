_NO_DOC_SOURCE = '"""A hand-written strategy."""\n\nimport math\n'


@pytest.fixture()
def artifact_dir(tmp_path, monkeypatch):
    """A temporary SELENE_ARTIFACT_DIR seeded with the fixture headers."""
    (tmp_path / "ARBUSDT_autogen_factor.py").write_text(_ARB_HEADER, encoding="utf-8")
    (tmp_path / "BROKENUSDT_autogen_factor.py").write_text(
        _MISSING_NAME_HEADER, encoding="utf-8"
    )
    (tmp_path / "handwritten.py").write_text(_NO_DOC_SOURCE, encoding="utf-8")
    monkeypatch.setenv("SELENE_ARTIFACT_DIR", str(tmp_path))
    return tmp_path


def test_load_artifact_strategy_success_path_sign_thresholds(artifact_dir) -> None:
    strategy = load_artifact_strategy("ARBUSDT_autogen_factor")
    assert isinstance(strategy, AlphaFormulaStrategy)
    assert strategy._name == "ARBUSDT_autogen_factor"
    # SIGN-terminal chain: sigmoid maps {-1,0,1} exactly onto {SELL,HOLD,BUY}
    assert strategy.buy_threshold == 0.6
    assert strategy.sell_threshold == 0.4
    assert len(strategy.formula_tokens) == 8


def test_load_artifact_strategy_request_params_override(artifact_dir) -> None:
    strategy = load_artifact_strategy("ARBUSDT_autogen_factor", buy_th=0.9, sell_th=0.1)
    assert strategy.buy_threshold == 0.9
    assert strategy.sell_threshold == 0.1


def test_load_artifact_strategy_missing_file_raises(artifact_dir) -> None:
    with pytest.raises(UnsupportedArtifact) as excinfo:
        load_artifact_strategy("NOPE_autogen_factor")
    assert "NOPE_autogen_factor" in str(excinfo.value)


def test_load_artifact_strategy_lists_every_missing_name(artifact_dir) -> None:
    with pytest.raises(UnsupportedArtifact) as excinfo:
        load_artifact_strategy("BROKENUSDT_autogen_factor")
    message = str(excinfo.value)
    assert "DEFINITELY_NOT_A_TOKEN" in message
    assert "ALSO_MISSING" in message


def test_no_docstring_source_errors_clearly(artifact_dir) -> None:
    with pytest.raises(UnsupportedArtifact):
        load_artifact_strategy("handwritten")


def test_rpn_stack_gate_catches_terminal_stack_2_under_intermediate_vocab() -> None:
    """The PENGU chain under the *intermediate* vocab (TS_STD_20 as a feature)
    reduces to a terminal stack of 2 — the gate must refuse it.

    This pins the review-caught decision that TS_STD_20 is an operator:
    feature-izing it lets GATE underflow the intended reduction and the VM
    returns None mid-chain, silently degrading every downstream consumer.
    """
    intermediate = FormulaVocab(
        feature_names=tuple(FEATURE_NAMES) + ("TS_STD_20",),
        operator_names=tuple(
            n for n in FORMULA_VOCAB.operator_names if n != "TS_STD_20"
        ),
    )
    tokens = [
        intermediate.token_names.index(n)
        for n in (
            "VWAP_DEV",
            "MACD_HIST",
            "TRIX_15",
            "HMA_DEV_20",
            "MUL",
            "ABS",
            "TS_STD_20",
            "GATE",
        )
    ]
    with pytest.raises(UnsupportedArtifact) as excinfo:
        rpn_stack_gate(intermediate, tokens)
    message = str(excinfo.value)
    assert "stack size 2" in message


def test_rpn_stack_gate_accepts_the_real_artifact_chains() -> None:
    """Both producer chains must survive the gate under the shipped vocab."""
    from selene_space_alpha.artifact_bridge import resolve, to_tokens

    arb = to_tokens(
        resolve(
            [
                "ICHIMOKU_KIJUN_DEV",
                "GK_VOL",
                "RET_ENTROPY_20",
                "RVOL",
                "MUL",
                "TS_MIN_10",
                "GATE",
                "SIGN",
            ]
        )
    )
    pengu = to_tokens(
        resolve(
            [
                "VWAP_DEV",
                "MACD_HIST",
                "TRIX_15",
                "HMA_DEV_20",
                "MUL",
                "ABS",
                "TS_STD_20",
                "GATE",
            ]
        )
    )
    rpn_stack_gate(FORMULA_VOCAB, arb)
    rpn_stack_gate(FORMULA_VOCAB, pengu)


def test_default_thresholds_by_terminal_operator() -> None:
    sign_tokens = [FORMULA_VOCAB.token_names.index(n) for n in ("RET", "SIGN")]
    assert default_thresholds(FORMULA_VOCAB, sign_tokens) == (0.6, 0.4)

    continuous_tokens = [FORMULA_VOCAB.token_names.index(n) for n in ("RET", "ABS")]
    assert default_thresholds(FORMULA_VOCAB, continuous_tokens) == (0.85, 0.45)
