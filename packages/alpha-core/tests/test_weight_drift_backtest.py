"""Weight-drift quantile backtest: golden parity + cost model + boundaries.

Compares the Selene pandas port (``selene_space_factor_research.mining.weight_drift_backtest``)
against fixtures generated by the real AlphaPurify polars implementation
(``scripts/gen_weight_drift_fixtures.py``).

Torch/polars independence:
- The port modules live in the standalone ``selene_space_factor_research.mining``
  package (no torch), but the tests still load them **by file path** through a
  synthetic package, and an AST pass asserts neither the port nor this test
  imports ``torch`` / ``polars``.
- Guard keys = ``ap_version`` + ``seed``; golden tolerance 1e-8 (plan §3.2).
"""
