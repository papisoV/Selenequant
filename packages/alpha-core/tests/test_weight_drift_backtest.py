# --------------------------------------------------------------------------
# Integration smoke: factor -> WeightDriftBacktest -> ic_decay.
# --------------------------------------------------------------------------
def test_integration_factor_backtest_ic_decay() -> None:
    ic = _load("ic_decay", _ALPHA_MINING)
    meta = _meta()
    factor_df = pd.read_parquet(FIX / meta["inputs"]["factor_df"])
    ret_df = pd.read_parquet(FIX / meta["inputs"]["ret_df"])
    res = WeightDriftBacktest().run(factor_df, ret_df, _fixture_config(meta))
    assert isinstance(res, WeightDriftResult)

    sym = factor_df["symbol"].iloc[0]
    sig = factor_df[factor_df["symbol"] == sym].sort_values("trade_date").set_index("trade_date")["factor"]
    r = ret_df[ret_df["symbol"] == sym].sort_values("trade_date").set_index("trade_date")["fut_ret_1"]
    decay = ic.compute_ic_decay(sig, r, max_lag=5)
    assert -1 <= decay.peak_ic <= 1
    assert decay.ic_by_lag.index.tolist() == [1, 2, 3, 4, 5]
