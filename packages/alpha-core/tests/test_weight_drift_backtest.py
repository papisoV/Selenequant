def test_cost_model_three_way_mapping() -> None:
    cm = AShareCostModel()
    cfg = WeightDriftConfig(tax_rate=0.001, fee_rate=0.0003, slippage_rate=0.001)
    cfg.tax_rate_direction = "both"
    assert cm.compute_buy_sell_fee(cfg) == (0.0023, 0.0023)
    cfg.tax_rate_direction = "buy"
    assert cm.compute_buy_sell_fee(cfg) == (0.0023, 0.0013)
    cfg.tax_rate_direction = "sell"
    assert cm.compute_buy_sell_fee(cfg) == (0.0013, 0.0023)


def test_cost_model_illegal_direction() -> None:
    cm = AShareCostModel()
    with pytest.raises(ValueError, match="tax_rate_direction"):
        cm.compute_buy_sell_fee(WeightDriftConfig(tax_rate_direction="nonsense"))


