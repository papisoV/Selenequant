"""Avellaneda-Stoikov (2008) optimal market making model.

Implements the AS reservation price, optimal spread, and optimal quote depths
from "High-Frequency Trading in a Limit Order Book" (Avellaneda & Stoikov, 2008).

Key formulas:
    Reservation price:  r = mid - q * gamma * sigma^2 * (T - t)
    Optimal depth:      delta = (1/gamma) * ln(1 + gamma/k)
    Optimal spread:     spread = gamma * sigma^2 * (T - t) + 2 * delta
"""

from __future__ import annotations

from dataclasses import dataclass
import math


@dataclass(frozen=True)
class ASParams:
    """Parameters for the Avellaneda-Stoikov market making model.

    Attributes:
        sigma: Volatility of the underlying asset (annualized).
        T: Trading period length (e.g. 1.0 for one unit of time).
        gamma: Risk aversion coefficient (higher = more conservative).
        k: Order book intensity parameter (arrival rate of market orders).
        q_max: Maximum allowed inventory (absolute value).
    """

    sigma: float
    T: float
    gamma: float
    k: float
    q_max: float


@dataclass
class ASQuotes:
    """Bid/ask quotes generated by the Avellaneda-Stoikov model.

    Attributes:
        bid_price: Optimal bid price.
        ask_price: Optimal ask price.
        spread: Difference between ask and bid prices.
        reservation_price: AS reservation price (indifference price).
        bid_size: Size to place on the bid side.
        ask_size: Size to place on the ask side.
    """

    bid_price: float
    ask_price: float
    spread: float
    reservation_price: float
    bid_size: float
    ask_size: float


def as_reservation_price(
    mid: float,
    sigma: float,
    T: float,
    gamma: float,
    q: float,
    t: float,
) -> float:
    """Compute the Avellaneda-Stoikov reservation price.

    The reservation price is the indifference price at which a market maker
    with inventory q is willing to hold the position. It adjusts the mid
    price downward when long (q > 0) and upward when short (q < 0).

    Formula: r = mid - q * gamma * sigma^2 * (T - t)

    Args:
        mid: Current mid price.
        sigma: Volatility of the underlying.
        T: Total trading period length.
        gamma: Risk aversion coefficient.
        q: Current inventory (positive = long, negative = short).
        t: Current time within the trading period (0 <= t <= T).

    Returns:
        The reservation price.
    """
    remaining = max(T - t, 0.0)
    return mid - q * gamma * sigma * sigma * remaining


def as_optimal_spread(
    sigma: float,
    T: float,
    gamma: float,
    k: float,
    t: float,
) -> float:
    """Compute the AS optimal spread (symmetric case).

    The optimal spread is the sum of the bid and ask depths from the
    reservation price. In the symmetric case (q=0), both depths are equal.

    Formula: spread = gamma * sigma^2 * (T - t) + (2/gamma) * ln(1 + gamma/k)

    Args:
        sigma: Volatility of the underlying.
        T: Total trading period length.
        gamma: Risk aversion coefficient.
        k: Order book intensity parameter.
        t: Current time within the trading period.

    Returns:
        The optimal spread.
    """
    remaining = max(T - t, 0.0)
    inventory_component = gamma * sigma * sigma * remaining
    # Risk-neutral (gamma=0) limit: depth_component → 0
    if gamma <= 0:
        return inventory_component
    depth_component = (2.0 / gamma) * math.log(1.0 + gamma / k)
    return inventory_component + depth_component


def as_optimal_depths(
    gamma: float,
    k: float,
) -> tuple[float, float]:
    """Compute optimal bid/ask depths (distance from reservation price).

    In the symmetric case, both depths are equal.

    Formula: delta_bid = delta_ask = (1/gamma) * ln(1 + gamma/k)

    Args:
        gamma: Risk aversion coefficient.
        k: Order book intensity parameter.

    Returns:
        A tuple of (delta_bid, delta_ask), both positive.
    """
    # Risk-neutral (gamma=0) limit: depth → 0 (no spread required)
    if gamma <= 0:
        return (0.0, 0.0)
    depth = (1.0 / gamma) * math.log(1.0 + gamma / k)
    return (depth, depth)


def as_quotes(
    mid: float,
    sigma: float,
    T: float,
    gamma: float,
    k: float,
    q: float,
    t: float,
) -> ASQuotes:
    """Generate full bid/ask quotes based on the AS model.

    Computes the reservation price, optimal depths, and derives final
    bid/ask prices. Default sizes are set to 1.0; use adjust_sizes()
    from the inventory module for inventory-aware sizing.

    Args:
        mid: Current mid price.
        sigma: Volatility of the underlying.
        T: Total trading period length.
        gamma: Risk aversion coefficient.
        k: Order book intensity parameter.
        q: Current inventory.
        t: Current time within the trading period.

    Returns:
        ASQuotes with bid/ask prices, spread, reservation price, and sizes.
    """
    r = as_reservation_price(mid, sigma, T, gamma, q, t)
    delta_bid, delta_ask = as_optimal_depths(gamma, k)
    bid_price = r - delta_bid
    ask_price = r + delta_ask
    spread = ask_price - bid_price
    return ASQuotes(
        bid_price=bid_price,
        ask_price=ask_price,
        spread=spread,
        reservation_price=r,
        bid_size=1.0,
        ask_size=1.0,
    )


def as_quotes_with_params(
    mid: float,
    q: float,
    t: float,
    params: ASParams,
) -> ASQuotes:
    """Convenience wrapper that generates AS quotes using an ASParams object.

    Args:
        mid: Current mid price.
        q: Current inventory.
        t: Current time within the trading period.
        params: ASParams containing sigma, T, gamma, k, q_max.

    Returns:
        ASQuotes with bid/ask prices, spread, reservation price, and sizes.
    """
    return as_quotes(mid, params.sigma, params.T, params.gamma, params.k, q, t)
