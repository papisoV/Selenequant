"""Stage C-2 end-to-end: REAL bb_v3 signal → LiveEngine.place_order → testnet FILLED.

Differs from stage_c1_e2e_ws_signal_live.py (which used WS kline close as a
fake signal trigger). This script wires a real BBV3Strategy instance into
the WS kline stream so signals are generated by actual strategy logic
(Bollinger Band crossover), then routes them through LiveEngine.

Flow:
    1. Load testnet credentials
    2. Build BinanceRESTClient + LiveExecutionEngine + OrderJournal
    3. Build BBV3Strategy with short periods (bb_len=5, buy_len=10) so
       signals trigger within ~10-15 minutes instead of 1h+
    4. Warm up strategy with REST historical klines (last 50 1m candles)
       so stddev is computable immediately
    5. Connect BinanceWSClient to testnet, subscribe btcusdt@kline_1m
    6. on_kline: feed KlineEvent to strategy.on_kline() → Signal | None
       If Signal and side is BUY/SELL → LiveEngine.place_order(MARKET)
    7. REST reconcile each placed order

Usage:
    call activate.bat
    python scripts/stage_c2_real_bb_v3_signal.py

    # Behind a proxy? Set it yourself — no default is assumed, so that a
    # machine without a proxy running is not silently pointed at a dead port.
    set SELENE_PROXY_URL=http://<host>:<port>
"""

