import os
import sys
import time
from pathlib import Path

_project_root = Path(__file__).resolve().parents[1]
_pkg_paths = [
    str(_project_root / "packages" / "exchange-sdk"),
    str(_project_root / "packages" / "shared-types"),
    str(_project_root / "packages" / "core"),
    str(_project_root / "packages" / "risk-engine"),
    str(_project_root / "packages" / "strategy-engine"),
    str(_project_root / "packages" / "market-data"),
]
for _p in _pkg_paths:
    if _p not in sys.path:
        sys.path.insert(0, _p)

for _mod_name in list(sys.modules.keys()):
    if _mod_name.startswith(("selene_space_exchange", "selene_space_strategy", "selene_space_types")):
        del sys.modules[_mod_name]

from selene_space_exchange.base.auth import ExchangeCredentials
from selene_space_exchange.base.rate_limiter import SlidingWindowRateLimiter
from selene_space_exchange.exchanges.binance.rest_client import BinanceRESTClient
from selene_space_exchange.exchanges.binance.ws_client import BinanceWSClient
from selene_space_exchange.execution.live_engine import LiveExecutionEngine
from selene_space_exchange.execution.order_journal import OrderJournal
from selene_space_exchange.trading import OrderSide, OrderType
from selene_space_strategy.templates.presets.bb_v3 import BBV3Strategy
from selene_space_types.market import KlineEvent
from selene_space_types.strategy import Signal

TESTNET_WS_URL = "wss://stream.testnet.binance.vision:9443/ws"
SYMBOL = "BTC/USDT"
BINANCE_SYMBOL = "BTCUSDT"
KLINE_INTERVAL = "1m"
ORDER_QTY = 0.001
WARMUP_KLINES = 60
MAX_RUNTIME_S = 1800  # 30 min max
JOURNAL_DIR = Path.home() / ".selenespace" / "journal_c2"


def _load_creds_from_env_file(env_path: Path) -> tuple[str, str]:
    api_key = ""
    api_secret = ""
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        k = k.strip()
        v = v.strip().strip('"').strip("'")
        if k == "SELENE_EXCHANGE_API_KEY":
            api_key = v
        elif k == "SELENE_EXCHANGE_API_SECRET":
            api_secret = v
    return api_key, api_secret


class C2Context:
    def __init__(self, rest_client, engine, journal, strategy):
        self.rest_client = rest_client
        self.engine = engine
        self.journal = journal
        self.strategy = strategy
        self.kline_count = 0
        self.signal_count = 0
        self.order_count = 0
        self.filled_orders: list[dict] = []


async def warmup_strategy(ctx: C2Context) -> None:
    """Fetch last N historical 1m klines from testnet REST and feed to strategy."""
    print(f"[WARMUP] Fetching {WARMUP_KLINES} historical {KLINE_INTERVAL} klines...")
    try:
        raw = await ctx.rest_client.get_klines(
            symbol=BINANCE_SYMBOL, interval=KLINE_INTERVAL, limit=WARMUP_KLINES
        )
    except Exception as exc:
        print(f"[WARMUP FAIL] {type(exc).__name__}: {exc}")
        return

    fed = 0
    for k in raw:
        # Binance kline format: [open_time, open, high, low, close, volume, close_time, ...]
        try:
            event = KlineEvent(
                exchange="binance",
                market_type="spot",
                symbol=SYMBOL,
                timestamp=int(k[0]),
                interval=KLINE_INTERVAL,
                open=float(k[1]),
                high=float(k[2]),
                low=float(k[3]),
                close=float(k[4]),
                volume=float(k[5]),
                closed=True,
            )
            ctx.strategy.on_kline(event)
            fed += 1
        except Exception:
            continue
    print(f"[WARMUP] Fed {fed} historical klines to strategy. "
          f"Bars in strategy: {len(ctx.strategy._bars)}")


async def on_kline(kline_event, ctx: C2Context):
    """Real bb_v3 signal pipeline: WS kline → strategy.on_kline → LiveEngine."""
    ctx.kline_count += 1

    try:
        kline = kline_event.kline if hasattr(kline_event, "kline") else kline_event
        close_price = getattr(kline, "close", None)
        closed = getattr(kline, "closed", False)
    except Exception:
        closed = True
        close_price = None

    print(f"[kline #{ctx.kline_count}] close={close_price} closed={closed}")

    if not closed:
        return

    signal: Signal | None = None
    try:
        signal = ctx.strategy.on_kline(kline_event) if hasattr(kline_event, "closed") else None
    except Exception as exc:
        print(f"[STRATEGY ERROR] {type(exc).__name__}: {exc}")
        return

    if signal is None:
        return

    ctx.signal_count += 1
    print(f"\n[SIGNAL #{ctx.signal_count}] side={signal.side} strength={signal.strength:.3f} "
          f"reason={signal.reason or '(none)'}")

    side = signal.side
    side_value = side.value if hasattr(side, "value") else str(side)
    if side_value not in ("buy", "sell"):
        print(f"[SKIP] Signal side {side_value!r} not actionable")
        return

    order_side = OrderSide.BUY if side_value == "buy" else OrderSide.SELL
    print(f"[PLACE_ORDER] Firing LiveEngine.place_order #{ctx.order_count + 1}...")
    try:
        order = await ctx.engine.place_order(
            account_id="c2-test",
            symbol=SYMBOL,
            side=order_side,
            order_type=OrderType.MARKET,
            quantity=ORDER_QTY,
            client_order_id=f"c2-bb-v3-{int(time.time() * 1000)}",
            signal_timestamp_ms=int(time.time() * 1000),
            strategy_id="bb-v3-stage-c2",
        )
        ctx.order_count += 1
        exchange_oid = ctx.engine._find_exchange_order_id(order.id)
        print(f"[FILLED?] internal_id={order.id} exchange_order_id={exchange_oid} "
              f"status={order.status}")

        await asyncio.sleep(2)
        try:
            rest_order = await ctx.rest_client.get_order(
                symbol=BINANCE_SYMBOL, order_id=exchange_oid
            )
            print(f"[RECONCILE] REST status={rest_order.get('status')} "
                  f"executedQty={rest_order.get('executedQty')}")
            if rest_order.get("status") == "FILLED":
                ctx.filled_orders.append(rest_order)
                print(f"[OK] FILLED via REST — orderId={rest_order.get('orderId')}")
        except Exception as exc:
            print(f"[RECONCILE FAIL] {exc}")

    except Exception as exc:
        print(f"[PLACE_ORDER FAIL] {type(exc).__name__}: {exc}")


async def main() -> int:
    api_key = os.environ.get("SELENE_EXCHANGE_API_KEY", "")
    api_secret = os.environ.get("SELENE_EXCHANGE_API_SECRET", "")
    if not api_key or not api_secret:
        env_path = _project_root / "services" / "local-api" / ".env"
        if env_path.exists():
            api_key, api_secret = _load_creds_from_env_file(env_path)
    if not api_key or not api_secret:
        print("[FAIL] No API credentials.")
        return 1

    print(f"[INFO] API key: {api_key[:8]}...{api_key[-4:]}")
    print(f"[INFO] Symbol: {SYMBOL}  Interval: {KLINE_INTERVAL}")
    print(f"[INFO] Order qty: {ORDER_QTY} BTC")
    print(f"[INFO] Journal: {JOURNAL_DIR}/order_journal.db")
    print()

    creds = ExchangeCredentials(api_key=api_key, api_secret=api_secret, passphrase=None)
    rate_limiter = SlidingWindowRateLimiter(calls_per_window=1200, window_ms=60_000)
    rest_client = BinanceRESTClient(
        credentials=creds, testnet=True, rate_limiter=rate_limiter
    )

    JOURNAL_DIR.mkdir(parents=True, exist_ok=True)
    journal = OrderJournal(journal_dir=JOURNAL_DIR)
    engine = LiveExecutionEngine(trading_client=rest_client, journal=journal)

    strategy = BBV3Strategy(
        symbol=SYMBOL,
        initial_capital=10000.0,
        bb_len=5,
        buy_len=10,
        buy_mult=2.0,
        sell_len=10,
        sell_mult=2.0,
        enable_long=True,
        enable_short=False,
        use_atr_stops=False,
        max_bars=200,
    )

    ctx = C2Context(rest_client=rest_client, engine=engine, journal=journal, strategy=strategy)

    await warmup_strategy(ctx)

    proxy_url = os.environ.get("SELENE_PROXY_URL") or os.environ.get("https_proxy")
    print(f"[INFO] WS proxy: {proxy_url or 'none (direct)'}")
    print(f"[INFO] WS URL: {TESTNET_WS_URL}")
    print()

    ws_client = BinanceWSClient(
        url=TESTNET_WS_URL,
        proxy_url=proxy_url,
        on_kline=lambda ev: on_kline(ev, ctx),
    )

    print("[STEP 1] Connecting to Binance testnet WS...")
    await ws_client.connect()
    print("[STEP 1] WS connected.")

    print(f"[STEP 2] Subscribing to {BINANCE_SYMBOL.lower()}@kline_{KLINE_INTERVAL}...")
    await ws_client.subscribe_kline(symbols=[BINANCE_SYMBOL], interval=KLINE_INTERVAL)
    print("[STEP 2] Subscribed.")

    print()
    print("=" * 60)
    print(f"Listening for real bb_v3 signals... (max {MAX_RUNTIME_S}s)")
    print("Press Ctrl+C to stop.")
    print("=" * 60)
    print()

    try:
        await asyncio.sleep(MAX_RUNTIME_S)
    except KeyboardInterrupt:
        print("\n[STOP] Interrupted by user.")

    print()
    print("=" * 60)
    print("Stage C-2 Summary")
    print("=" * 60)
    print(f"Klines received:    {ctx.kline_count}")
    print(f"Signals generated:  {ctx.signal_count}")
    print(f"Orders placed:      {ctx.order_count}")
    print(f"Orders FILLED:      {len(ctx.filled_orders)}")
    for o in ctx.filled_orders:
        print(f"  orderId={o.get('orderId')} side={o.get('side')} "
              f"executedQty={o.get('executedQty')} avgPrice={o.get('cummulativeQuoteQty')}")

    await ws_client.disconnect()
    return 0 if ctx.filled_orders else 2


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
